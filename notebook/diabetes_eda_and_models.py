x = df.drop('Outcome', axis=1)
y = df['Outcome']

x_train, x_test, y_train,y_test  = train_test_split(x, y, test_size=0.2, random_state=42)

model1=LogisticRegression()
model2=SVC()
model3=RandomForestClassifier()
model4=GradientBoostingClassifier(n_estimators=1000)

columns=['LogisticRegression','SVC','RandomForestClassifier','GradientBoostingClassifier']
result1=[]
result2=[]
result3=[]

def cal (model1):
  model1.fit(x_train ,y_train)
  pre=model1.predict(x_test)
  accuracy = accuracy_score(y_test, pre)
  recall = recall_score(y_test, pre)
  f1 = f1_score(y_test, pre)

  result1.append(accuracy)
  result2.append(recall)
  result3.append(f1)

  sns.heatmap(confusion_matrix(y_test, pre), annot=True)
  print(model1)
  print('accuracy is:', accuracy, 'recall is:', recall, 'f1 is:', f1)
cal( model1)

cal(model2)

cal(model3)

cal(model4)

result1

result2

result3

FinalResults=pd.DataFrame({'Algorithm':columns,'Accuracies':result1,'Recalls':result2,'F1_score':result3 })

fig,ax=plt.subplots(figsize=(20,5))
plt.plot(FinalResults.Algorithm,result1,label='Accuracy')
plt.plot(FinalResults.Algorithm,result2,label='Recall')
plt.plot(FinalResults.Algorithm,result3,label='F1_score')
plt.legend()
plt.show()

